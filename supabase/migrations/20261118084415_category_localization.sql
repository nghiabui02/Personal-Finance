-- Applies only to the ten shared rows inspected on 2026-11-18.
-- The fingerprint includes UUIDs, names, types, default flags and system keys;
-- names locate rows only after that exact inventory has been verified.
set local lock_timeout = '5s';
lock table public.categories in share row exclusive mode;

create temporary table localization_category_inventory (
  default_key text primary key, name text not null, type text not null
) on commit drop;
insert into localization_category_inventory values
  ('salary', 'Salary', 'income'),
  ('bonus', 'Bonus', 'income'),
  ('investment', 'Investment', 'income'),
  ('other_income', 'Other Income', 'income'),
  ('food_drink', 'Food & Drinks', 'expense'),
  ('transport', 'Transport', 'expense'),
  ('shopping', 'Shopping', 'expense'),
  ('entertainment', 'Entertainment', 'expense'),
  ('health', 'Health', 'expense'),
  ('other_expense', 'Other Expense', 'expense');

do $$
declare
  inventory_fingerprint text;
begin
  select encode(sha256(convert_to(string_agg(
    jsonb_build_array(id, name, type, is_default, system_key)::text,
    E'\n' order by id
  ), 'UTF8')), 'hex') into inventory_fingerprint
  from public.categories where user_id is null;

  if inventory_fingerprint is distinct from 'e5b0f04cf313f114b92edabac5f31151a10f1bf6ed6c8ea7f47319633460f217'
    or exists (
      select 1 from localization_category_inventory i
      left join public.categories c on c.user_id is null and c.name = i.name and c.type = i.type
      where c.id is null or not c.is_default or c.system_key is not null
    ) then
    raise exception 'Category inventory changed. Review shared IDs, names and types before applying localization.';
  end if;
end;
$$;

alter table public.categories
  add column default_key text check (default_key in (
    'salary', 'bonus', 'investment', 'other_income', 'food_drink', 'transport',
    'shopping', 'entertainment', 'health', 'housing', 'education', 'bills', 'other_expense'
  )),
  add column name_is_custom boolean not null default false;

update public.categories c set default_key = i.default_key
from localization_category_inventory i
where c.user_id is null and c.name = i.name and c.type = i.type;
create unique index categories_shared_default_key_unique
  on public.categories (default_key) where user_id is null and default_key is not null;
alter table public.categories add constraint categories_default_key_shared check (default_key is null or user_id is null);

-- Only exact per-key names generated by the app are candidates for translation.
-- Vietnamese/other legacy names remain custom. No existing name is rewritten.
update public.categories set name_is_custom = true
where user_id is not null and (
  system_key is null or name is distinct from case system_key
    when 'lend_out' then 'Lend' when 'borrow_in' then 'Borrow'
    when 'collect_debt' then 'Collect Debt' when 'repay_debt' then 'Repay Debt'
    when 'adjust_up' then 'Balance Adjustment' when 'adjust_down' then 'Balance Adjustment'
  end
);

create function public.mark_category_custom_name() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.name is distinct from old.name then
    new.name_is_custom := true;
  end if;
  return new;
end;
$$;
create trigger categories_custom_name before update on public.categories
  for each row execute function public.mark_category_custom_name();
